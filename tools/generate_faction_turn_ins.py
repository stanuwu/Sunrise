"""Generate the archived faction XP rates for build 86657.20.08.23.1800-9.

Use DestinyFactionDefinition.json and DestinyVendorDefinition.json (plain or gzipped)
from https://storage.manifest.report/manifest-archive/versions/83e9ee00-d5d1-453c-b454-ea08c1acefb4/tables/.
"""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

# SHA-256 of the uncompressed Bungie faction and vendor table files for this build.
FACTION_SHA256 = "8f6a3ec405b8c891935764e4a3c27a202029207f9d951c2054e6ae135bf2288e"
VENDOR_SHA256 = "649c78fc84b97070c7e859d6d587f162d7264a21f403d319de5a087d6ccc05c1"

# Vendors whose faction-material exchanges Sunrise supports.
VENDORS = (69482069, 3603221665, 672118013, 396892126)  # Zavala, Shaxx, Banshee, Devrim
RESOURCE = Path(__file__).resolve().parents[1] / "Sunrise/resources/database/faction_turn_in_content.sql"
SCHEMA = """-- Generated by tools/generate_faction_turn_ins.py for build 86657.20.08.23.1800-9.
CREATE TABLE faction_turn_ins (
    faction_hash INTEGER NOT NULL,
    placeholder_hash INTEGER NOT NULL,
    cost_hash INTEGER NOT NULL,
    xp_per_unit INTEGER NOT NULL,
    PRIMARY KEY (faction_hash, placeholder_hash, cost_hash)
) WITHOUT ROWID;

INSERT INTO faction_turn_ins VALUES
"""


def read_table(path: Path, digest: str) -> dict:
    """Verify the archived bytes before using any rows."""
    data = path.read_bytes()
    if path.suffix == ".gz":
        data = gzip.decompress(data)
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"{path}: unexpected manifest table digest")
    return json.loads(data)


def generate(factions: dict, vendors: dict) -> str:
    """Join single-currency vendor sales to their faction's XP per material."""
    rows = set()
    for vendor_hash in VENDORS:
        vendor = vendors[str(vendor_hash)]
        faction_hash = vendor["factionHash"]
        rates = factions[str(faction_hash)]["tokenValues"]
        for sale in vendor["itemList"]:
            costs = sale["currencies"]
            if len(costs) == 1:
                payment = costs[0]["itemHash"]
                rate = rates.get(str(payment))
                if rate is not None:
                    rows.add((faction_hash, sale["itemHash"], payment, rate))
    return SCHEMA + ",\n".join("    (%d, %d, %d, %d)" % row for row in sorted(rows)) + ";\n"


def main() -> None:
    """Regenerate the embedded resource or check that it matches the input tables."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("faction", type=Path)
    parser.add_argument("vendor", type=Path)
    parser.add_argument("--check", action="store_true", help="compare with the checked-in SQL")
    args = parser.parse_args()
    try:
        factions = read_table(args.faction, FACTION_SHA256)
        vendors = read_table(args.vendor, VENDOR_SHA256)
        sql = generate(factions, vendors)
        if args.check:
            if RESOURCE.read_text(encoding="utf-8") != sql:
                parser.exit(1, "Faction turn-in SQL differs from the pinned manifest.\n")
        else:
            RESOURCE.write_bytes(sql.encode("utf-8"))
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
